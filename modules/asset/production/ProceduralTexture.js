import { encodePngRgba } from '../../../foundation/PngRgba.js';
import { proceduralTextureSchema, PROCEDURAL_TEXTURE_PALETTES } from '../model/ProceduralTextureContract.js';

const TAU=2*Math.PI;
const clamp=v=>Math.max(0,Math.min(1,v));
const lerp=(a,b,t)=>a+(b-a)*t;
const smooth=t=>t*t*(3-2*t);
const wrap=(n,p)=>(n%p+p)%p;
const rgb=hex=>[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16));

function hash(x,y,seed){
  let n=(Math.imul(x+1,0x9e3779b1)^Math.imul(y+1,0x85ebca6b)^seed)>>>0;
  n=Math.imul(n^(n>>>16),0x7feb352d);
  n=Math.imul(n^(n>>>15),0x846ca68b);
  return ((n^(n>>>16))>>>0)/4294967295;
}

// Periodic lattice noise: UV coordinates wrap without a discontinuity.
function noise(u,v,px,py,seed){
  const x=u*px,y=v*py,ix=Math.floor(x),iy=Math.floor(y);
  const tx=smooth(x-ix),ty=smooth(y-iy);
  const sample=(a,b)=>hash(wrap(a,px),wrap(b,py),seed);
  return lerp(lerp(sample(ix,iy),sample(ix+1,iy),tx),lerp(sample(ix,iy+1),sample(ix+1,iy+1),tx),ty);
}

function samplePattern({pattern,seed,frequency:f},u,v){
  const n=(x,y,s=0)=>noise(u,v,x*f,y*f,(seed+s)>>>0);
  if(pattern==='wood'){
    const distortion=n(3,2,17);
    const grain=.5+.5*Math.sin(TAU*(u*9*f+distortion*.8+n(12,3,31)*.13));
    return clamp(.48*grain+.38*n(20,3)+.14*n(45,5,5));
  }
  if(pattern==='stone')return clamp(.5*n(5,5)+.3*n(13,13,13)+.2*n(37,37,23));
  if(pattern==='fabric'){
    const a=Math.sin(TAU*u*8*f),b=Math.sin(TAU*v*8*f);
    const weave=.5+.5*a*b;
    return clamp(.72*weave+.28*n(23,23,11));
  }
  return clamp(.72*n(42,3)+.2*n(18,2,19)+.08*n(12,12,7));
}

/** Pure, bounded, reproducible UV texture generation. No renderer or network. */
export function generateProceduralTexture(input){
  const spec=proceduralTextureSchema.parse(input),size=spec.resolution;
  const palette=PROCEDURAL_TEXTURE_PALETTES[spec.pattern];
  const dark=rgb(spec.darkColor??palette[0]),light=rgb(spec.lightColor??palette[1]);
  const height=new Float32Array(size*size);
  const base=new Uint8Array(size*size*4);
  const normal=spec.normalStrength?new Uint8Array(base.length):null;
  for(let y=0;y<size;y++)for(let x=0;x<size;x++){
    const i=y*size+x,t=samplePattern(spec,(x+.5)/size,(y+.5)/size);
    height[i]=t;
    const shade=lerp(.5,t,spec.contrast);
    for(let c=0;c<3;c++)base[i*4+c]=Math.round(lerp(dark[c],light[c],shade));
    base[i*4+3]=255;
  }
  if(normal){
    const at=(x,y)=>height[wrap(y,size)*size+wrap(x,size)];
    for(let y=0;y<size;y++)for(let x=0;x<size;x++){
      const i=(y*size+x)*4;
      const nx=-(at(x+1,y)-at(x-1,y))*spec.normalStrength*4;
      const ny=(at(x,y+1)-at(x,y-1))*spec.normalStrength*4;
      const len=Math.hypot(nx,ny,1);
      normal.set([Math.round((nx/len*.5+.5)*255),Math.round((ny/len*.5+.5)*255),Math.round((1/len*.5+.5)*255),255],i);
    }
  }
  return {size,baseColor:encodePngRgba(base,size,size),
    normal:normal?encodePngRgba(normal,size,size):null};
}

/** Cache only within a single compile; the GLB owns the generated bytes. */
export function attachProceduralTexture(document,material,spec,cache){
  const key=JSON.stringify(spec);
  let textures=cache.get(key);
  if(!textures){
    const {baseColor,normal}=generateProceduralTexture(spec);
    textures={
      base:document.createTexture(spec.pattern+'-color').setMimeType('image/png').setImage(baseColor),
      normal:normal?document.createTexture(spec.pattern+'-normal').setMimeType('image/png').setImage(normal):null
    };
    cache.set(key,textures);
  }
  material.setBaseColorTexture(textures.base);
  if(textures.normal)material.setNormalTexture(textures.normal);
}
