import {test,expect} from '@playwright/test';

test('code workbench keeps key actions visible, supports save-and-run, and restores its collapsed sidebar',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/studio/?page=world');
  await expect(page.locator('#runtime-status')).toHaveAttribute('data-state','ready',{timeout:60000});
  await page.getByRole('button',{name:'代码世界',exact:true}).click();
  const editor=page.getByLabel('完整代码项目');
  await expect(editor.getByText('开始创作',{exact:true})).toBeVisible();
  await editor.getByRole('button',{name:'新建代码世界',exact:true}).click();
  const source=editor.getByLabel('世界源码');
  await expect(source).toHaveValue(/createProject/);
  const run=editor.getByRole('button',{name:'运行代码世界',exact:true});
  await expect(run).toBeInViewport();
  await expect(editor.getByRole('button',{name:'保存源码草稿',exact:true})).toBeInViewport();
  await expect(editor.getByRole('button',{name:'保存世界状态',exact:true})).toBeInViewport();
  const width=await page.locator('.scene-panel').evaluate(el=>el.clientWidth);
  await page.getByRole('button',{name:'扩大源码区域',exact:true}).click();
  await expect.poll(()=>page.locator('.scene-panel').evaluate(el=>el.clientWidth)).toBeGreaterThan(width);
  const changed=(await source.inputValue())+'\n// Workbench RC user edit';
  await source.fill(changed);
  await expect(editor.getByText('未保存编辑',{exact:true})).toBeVisible();
  await expect(run).toBeEnabled();
  await source.press('Control+Enter');
  await expect(editor.locator('output')).toHaveText('代码世界运行中');
  await expect(page.locator('.studio-code-project-viewport canvas')).toBeVisible();
  await expect(source).toHaveValue(changed);
  await expect(editor.getByLabel('共享发布授权令牌')).toBeHidden();
  await expect(editor.getByRole('button',{name:'保存世界状态',exact:true})).toBeEnabled();
  await editor.getByRole('button',{name:'保存世界状态',exact:true}).click();
  await expect(editor.locator('output')).toHaveText('世界状态已保存到本机');
  await page.screenshot({path:testInfo.outputPath('workbench-after.png')});
  await page.getByRole('button',{name:'收起场景侧边栏',exact:true}).click();
  await expect(editor).toBeHidden();
  await page.getByRole('button',{name:'代码世界',exact:true}).click();
  await expect(editor).toBeVisible();
  await expect(source).toHaveValue(changed);
  await page.getByRole('button',{name:'恢复源码区域宽度',exact:true}).click();
  await expect.poll(()=>page.locator('.scene-panel').evaluate(el=>el.clientWidth)).toBe(width);
  await expect(run).toBeInViewport();
  expect(errors).toEqual([]);
});
